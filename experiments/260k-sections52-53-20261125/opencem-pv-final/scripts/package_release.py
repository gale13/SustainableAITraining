"""Verify an isolated installed copy, then create a checksummed portable archive."""
import csv,hashlib,json,os,re,shutil,subprocess,sys,tempfile,zipfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def files():
    for p in sorted(ROOT.rglob('*')):
        if not p.is_file() or '__pycache__' in p.parts or any(x.endswith('.egg-info') for x in p.parts):continue
        if 'build' in p.relative_to(ROOT).parts or p.suffix=='.pyc':continue
        yield p

def main():
    env=dict(os.environ,PIP_DISABLE_PIP_VERSION_CHECK='1',PYTHONDONTWRITEBYTECODE='1')
    tested=subprocess.run([sys.executable,'-m','unittest','discover','-s','tests','-v'],cwd=ROOT,
        env=dict(env,PYTHONPATH=str(ROOT/'src')),capture_output=True,text=True)
    (ROOT/'unit_tests.log').write_text(tested.stdout+tested.stderr)
    if tested.returncode:raise RuntimeError('Tests failed; see unit_tests.log')
    test_count=int(re.search(r'Ran (\d+) tests',tested.stderr).group(1))
    with tempfile.TemporaryDirectory(prefix='opencem-pv-install-') as temp:
        target=Path(temp)/'installed'
        install=subprocess.run([sys.executable,'-m','pip','install','--no-deps','--no-build-isolation',
            '--target',str(target),str(ROOT)],capture_output=True,text=True,env=env)
        (ROOT/'installation_check.log').write_text(install.stdout+install.stderr)
        if install.returncode:raise RuntimeError('Standalone installation failed; see installation_check.log')
        code='''import sys,json,hashlib
from pathlib import Path
sys.path.insert(0,sys.argv[1])
from opencem_pv import PVDatabase
from opencem import dataset
with PVDatabase() as db:
    assert len(db.days())==242
    assert len(db.days(recommended_only=True))==142
    energy=db.load_day('2025-12-26').energy(36000,185.8)
    assert abs(energy-35565.43845128652)<1e-6
    manifest=json.loads(db.path.with_name('manifest.json').read_text())
    assert hashlib.sha256(db.path.read_bytes()).hexdigest()==manifest['database_sha256']
    source=Path(dataset.__file__).read_bytes()
    assert hashlib.sha1(f'blob {len(source)}\\0'.encode()+source).hexdigest()=='13fc1b1e9aa03faa4b1e471f4c2c96db60cc16bf'
    print(json.dumps(dict(installed_import_ok=True,bundled_database_ok=True,official_code_hash_ok=True,
        dates=242,recommended_dates=142,example_energy_j=energy)))
'''
        checked=subprocess.run([sys.executable,'-c',code,str(target)],cwd=temp,env=env,text=True,capture_output=True)
        if checked.returncode:raise RuntimeError(checked.stdout+checked.stderr)
        verification=json.loads(checked.stdout)
    # These directories are generated by pip for this new distribution only.
    for path in [ROOT/'build',ROOT/'src/opencem_pv_trajectories.egg-info']:
        if path.exists():shutil.rmtree(path)
    with (ROOT/'examples/profiling04_smoke.csv').open() as f:smoke_count=sum(1 for _ in csv.DictReader(f))
    with (ROOT/'examples/pv_2025-12-26_60s.csv').open() as f:export=list(csv.DictReader(f))
    verification.update(unit_tests_passed=test_count,unit_test_command='PYTHONPATH=src python -m unittest discover -s tests -v',
        simulator_smoke_epochs=smoke_count,cli_export_rows=len(export),cli_export_missing=sum(not row['pv_power_w'] for row in export))
    (ROOT/'verification.json').write_text(json.dumps(verification,indent=2)+'\n')
    checksums={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in files() if p.name!='checksums.json'}
    (ROOT/'checksums.json').write_text(json.dumps(checksums,indent=2)+'\n')
    archive=ROOT.parent/'opencem-pv-final-v1.0.0.zip'
    with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as z:
        for p in files():z.write(p,Path(ROOT.name)/p.relative_to(ROOT))
    with zipfile.ZipFile(archive) as z:
        assert z.testzip() is None
    archive.with_suffix('.zip.sha256').write_text(hashlib.sha256(archive.read_bytes()).hexdigest()+'  '+archive.name+'\n')
    print(json.dumps(dict(verification=verification,archive=str(archive),archive_bytes=archive.stat().st_size),indent=2))

if __name__=='__main__':main()
